"""Baseline snapshot: the published numbers later stages must match.
=================================================================
Reads only the committed JSON in frontend/data/ (no network, no recalculation)
and writes docs/architecture/baseline-YYYY-MM-DD.json, dated by the data's
lastUpdated stamp. V2.0 reconciles its new pipeline against this file.

    venv/Scripts/python scripts/make_baseline.py

Every rate is stored next to its sample (games). Definitions are copied into the
file so it can be read on its own.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'frontend' / 'data'
OUT_DIR = ROOT / 'docs' / 'architecture'


def load(rel):
    with open(DATA / rel, encoding='utf-8') as f:
        return json.load(f)


def git(*args):
    try:
        return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def block(b):
    """Games, penalties, yards and per-game rates from a season block."""
    if not b:
        return None
    return {k: b.get(k) for k in ('games', 'penalties', 'yards', 'perGame', 'yardsPerGame', 'yardsPerPenalty')}


def main():
    stats = load('stats.json')
    trends = load('trends.json')
    sc = load('season_comparison.json')
    teams_index = sorted(p.stem for p in (DATA / 'teams').glob('*.json') if p.stem != 'index')
    card = load('scorecard/public.json')
    stamp = load('source_stamp.json')

    date = (stats.get('lastUpdated') or '')[:10]
    if not date:
        sys.exit('stats.json has no lastUpdated; cannot date the baseline')

    teams = []
    for abbr in teams_index:
        t = load(f'teams/{abbr}.json')
        cur = t.get('current') or {}
        teams.append({
            'team': abbr,
            'rankCurrent': (t.get('rank') or {}).get('current'),
            'rankLastSeason': (t.get('rank') or {}).get('lastSeason'),
            'rankOf': (t.get('rank') or {}).get('of'),
            'games': cur.get('games'),
            'penalties': cur.get('penalties'),
            'perGame': cur.get('perGame'),
            'drawnPerGame': cur.get('drawnPerGame'),
        })
    teams.sort(key=lambda r: (r['rankCurrent'] is None, r['rankCurrent']))

    crews = [{'name': c['name'], 'slug': c['slug'], **block(c.get('current')),
              'lastSeason': block((c.get('baselines') or {}).get('lastSeason'))}
             for c in sc.get('crewChiefs', [])]
    crews.sort(key=lambda r: -(r['perGame'] or 0))

    def card_summary(s):
        return {'season': s.get('season'), **(s.get('summary') or {})} if s else None

    out = {
        'about': 'Published numbers as of this data commit. Later stages must reproduce them '
                 'or explain each difference. Generated by scripts/make_baseline.py; do not hand-edit.',
        'source': {
            'commit': git('log', '-1', '--format=%H', '--', 'frontend/data'),
            'commitDate': git('log', '-1', '--format=%cI', '--', 'frontend/data'),
            'dataLastUpdated': stats.get('lastUpdated'),
            'nflversePbpUpdated': stamp.get('pbp'),
        },
        'definitions': {
            'flag': 'A play-by-play row with penalty == 1 (nflverse), counted once per play. A second flag '
                    'on the same play (usually a declined one) is not counted again.',
            'leagueBySeason': 'trends.json bySeason: regular season only (since #117); games = '
                              'games with at least one flag.',
            'currentSeason': 'season_comparison.json: regular season only, accepted penalties, through the '
                             'last completed week.',
            'teamRank': 'teams/<ABBR>.json rank.current: 1 = most flags committed per game this season, of 32.',
            'scorecard': 'scorecard/public.json: live = projections frozen before kickoff; backtest = '
                         'reconstructed from data before each week.',
        },
        'headline': {k: stats.get(k) for k in ('totalPenalties', 'totalGames', 'totalReferees', 'seasonsRange',
                                               'refereeVariance')},
        'leagueBySeason': trends.get('bySeason'),
        'currentSeason': {
            'season': sc.get('currentSeason'),
            'throughWeek': sc.get('throughWeek'),
            'regularSeasonOnly': sc.get('regularSeasonOnly'),
            'league': block((sc.get('league') or {}).get('current')),
            'leagueBaselines': {k: block(v) for k, v in ((sc.get('league') or {}).get('baselines') or {}).items()},
        },
        'crewChiefs': crews,
        'teams': teams,
        'scorecard': {
            'live': card_summary({'season': card.get('season'), **(card.get('live') or {})}),
            'backtestCurrentSeason': card_summary((card.get('backtest') or {}).get('currentSeason')),
            'backtestLastSeason': card_summary((card.get('backtest') or {}).get('lastSeason')),
        },
    }

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f'baseline-{date}.json'
    path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')
    print(f'Wrote {path.relative_to(ROOT).as_posix()}: {len(out["leagueBySeason"])} seasons, '
          f'{len(crews)} crew chiefs, {len(teams)} teams')


if __name__ == '__main__':
    main()
