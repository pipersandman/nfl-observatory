// node worker/gameday/bundle.mjs -> worker/gameday/worker.bundle.js (one file, for pasting into the Cloudflare dashboard)
import { readFileSync, writeFileSync } from 'fs';
const dir = new URL('.', import.meta.url).pathname;
const parse = readFileSync(dir + 'parse.js', 'utf8').replace(/^export /gm, '');
const worker = readFileSync(dir + 'worker.js', 'utf8').replace(/^import .*parse\.js';\n/m, '');
writeFileSync(dir + 'worker.bundle.js', `// GENERATED by bundle.mjs from parse.js + worker.js. Paste this whole file into the Cloudflare Worker editor.\n${parse}\n${worker}`);
console.log('wrote worker.bundle.js');
